#!/usr/bin/env python3
"""Generate deterministic, path-only retrieval maps from Git's tracked index.

Untracked vault contents are never scanned. Stage intended additions before refresh.
"""
from pathlib import Path, PurePosixPath
import argparse
import json
import os
import subprocess
from urllib.parse import quote

OUTPUTS = ('docs/high_signal_file_index.json', 'docs/codebase-overview.md', 'llms.txt')


def inventory(root):
    result = subprocess.run(['git', '-C', str(root), 'ls-files', '--cached', '-z'],
                            check=True, capture_output=True, timeout=30,
                            env={k: v for k, v in os.environ.items() if not k.startswith('GIT_')})
    paths = set(result.stdout.decode('utf-8').rstrip('\0').split('\0')) - {''}
    paths.update(OUTPUTS)
    for name in sorted(paths):
        path = PurePosixPath(name)
        if path.is_absolute() or '..' in path.parts or any(ord(c) < 32 for c in name):
            raise ValueError(f'Unsupported tracked path: {name!r}')
        target = root / name
        if any((root.joinpath(*path.parts[:i])).is_symlink() for i in range(1, len(path.parts)+1)):
            raise ValueError(f'Linked tracked path: {name!r}')
        if name not in OUTPUTS and not target.is_file():
            raise ValueError(f'Missing tracked file: {name!r}; stage intentional removals first')
    return sorted(paths)


def render(paths):
    rows = [{'path': name, 'component': name.split('/')[0] if '/' in name else '(root)',
             'kind': 'source' if Path(name).suffix in {'.py', '.sh'} else 'reference'} for name in paths]
    machine = json.dumps({'format': 1, 'scope': 'Git tracked/staged paths only; no content or embeddings',
                          'files': rows}, indent=2, ensure_ascii=False) + '\n'
    overview = ['# Codebase overview', '', 'Generated by `python3 scripts/doc_indexes.py` from tracked/staged paths. '
                'No vault body text is read. Stage intended additions/removals before regenerating.', '']
    for group in sorted({row['component'] for row in rows}):
        overview.extend(['## ' + group, ''])
        for row in rows:
            if row['component'] == group:
                label = row['path'].replace('\\', '\\\\').replace('[', '\\[').replace(']', '\\]')
                overview.append('- [' + label + '](../' + quote(row['path'], safe='/.-_~') + ')')
        overview.append('')
    llms = ['# COG repository guide', '', 'Path-only offline retrieval map. No private vault body text or embeddings.',
            '', 'See docs/DEVELOPMENT.md for validation and docs/AGENT-SUPPORT.md for agent surfaces.', '']
    llms.extend('- ' + name for name in paths)
    return dict(zip(OUTPUTS, [machine, '\n'.join(overview), '\n'.join(llms) + '\n']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed maps are stale; never write')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    try:
        outputs = render(inventory(root))
        stale = []
        for name, content in outputs.items():
            target = root / name
            if args.check:
                if not target.is_file() or target.read_text(encoding='utf-8') != content:
                    stale.append(name)
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding='utf-8')
        if stale:
            parser.exit(1, 'Stale retrieval maps: ' + ', '.join(stale) + '\n')
        print('Retrieval maps verified' if args.check else 'Retrieval maps refreshed')
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, f'Retrieval map error: {error}\n')


if __name__ == '__main__':
    main()
